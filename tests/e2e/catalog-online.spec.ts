import { expect, test } from '@playwright/test';
import { closeDetail, enableOnline, navigate, exportBackup } from './helpers';
import { mockLookup } from './fixtures';

test.use({ serviceWorkers: 'block' });

async function addProviderBook(page: import('@playwright/test').Page) {
  await navigate(page, 'My library');
  await page.getByRole('button', { name: 'Add a book', exact: true }).first().click();
  const add = page.getByRole('dialog', { name: 'Add a book', exact: true });
  await add.getByLabel('Search title, author or ISBN', { exact: true }).fill('A Field Guide to Thinking');
  await add.getByRole('button', { name: 'Search', exact: true }).click();
  await add.getByRole('button', { name: /A Field Guide to Thinking.*Select/ }).click();
  await add.getByRole('button', { name: 'Find editions', exact: true }).click();
  await expect(add.getByLabel('Choose edition', { exact: true })).toBeVisible();
  await add.getByLabel('Choose edition', { exact: true }).selectOption('/books/OL1M');
  await add.getByLabel('Title', { exact: true }).fill('My Corrected Thinking Title');
  await add.getByLabel('Page count', { exact: true }).fill('250');
  await add.getByRole('button', { name: 'Save book', exact: true }).click();
  await expect(add).not.toBeVisible();
  return page.getByRole('dialog', { name: 'My Corrected Thinking Title', exact: true });
}

test('mocked metadata correction and personal organization survive field-diff refresh', async ({ page }) => {
  await mockLookup(page);
  await page.goto('/');
  await enableOnline(page);
  const detail = await addProviderBook(page);
  await expect(detail.getByLabel('Page count', { exact: true })).toHaveValue('250');
  await detail.getByRole('combobox', { name: 'Primary Layer', exact: true }).selectOption('operating-system');
  await detail.getByLabel('Reading purpose', { exact: true }).fill('Practice better thinking, by my choice.');
  await detail.getByRole('checkbox', { name: /^Mind-Expanding/ }).check();
  await detail.getByRole('button', { name: 'Save details', exact: true }).click();
  await expect(detail.getByText(/Origin: user/)).toBeVisible();
  const accept = detail.locator('.suggestion-row').filter({ hasText: 'Decision making' });
  await accept.getByRole('button', { name: 'Accept', exact: true }).click();
  const reject = detail.locator('.suggestion-row').filter({ hasText: 'Learning' });
  await reject.getByRole('button', { name: 'Reject', exact: true }).click();
  await expect(detail.getByRole('button', { name: 'Remove tag Decision making', exact: true })).toBeVisible();
  await mockLookup(page, true);
  await detail.getByRole('tab', { name: 'Sources', exact: true }).click();
  await expect(detail.getByText('Open Library reader rating', { exact: false })).toBeVisible();
  await expect(detail.getByText(/24 ratings/)).toBeVisible();
  await detail.getByRole('button', { name: 'Refresh metadata', exact: true }).click();
  await expect(detail.getByRole('heading', { name: 'Review provider changes', exact: true })).toBeVisible();
  await expect(detail.getByText('Provider: Updated Provider Title', { exact: true })).toBeVisible();
  await detail.getByRole('button', { name: 'Apply provider refresh', exact: true }).click();
  await expect(detail.getByRole('heading', { name: 'Review provider changes', exact: true })).not.toBeVisible();
  await detail.getByRole('tab', { name: 'Details', exact: true }).click();
  await expect(detail.getByLabel('Title', { exact: true })).toHaveValue('My Corrected Thinking Title');
  await expect(detail.getByRole('combobox', { name: 'Primary Layer', exact: true })).toHaveValue('operating-system');
  await expect(detail.getByRole('checkbox', { name: /^Mind-Expanding/ })).toBeChecked();
  await expect(detail.getByRole('button', { name: 'Remove tag Decision making', exact: true })).toBeVisible();
  await expect(detail.locator('.suggestion-row').filter({ hasText: 'Learning' })).toHaveCount(0);
  await closeDetail(page);
  const backup = await exportBackup(page);
  expect(backup.document.entities.tagAssignments.some(assignment => assignment.state === 'rejected')).toBe(true);
});

test('tag rename, merge and archive retain accepted book association without duplicate names', async ({ page }) => {
  await mockLookup(page);
  await page.goto('/');
  await enableOnline(page);
  const detail = await addProviderBook(page);
  await detail.locator('.suggestion-row').filter({ hasText: 'Decision making' }).getByRole('button', { name: 'Accept', exact: true }).click();
  await closeDetail(page);
  await navigate(page, 'Settings & backup');
  const row = page.locator('.tag-manager .suggestion-row').filter({ hasText: 'Decision making' });
  await row.getByRole('button', { name: 'Rename', exact: true }).click();
  await page.getByLabel('Rename tag', { exact: true }).fill('Decisions');
  await page.locator('.tag-manager form').getByRole('button', { name: 'Save', exact: true }).click();
  await page.getByLabel('Tag name', { exact: true }).fill('Thinking');
  await page.getByRole('button', { name: 'Create tag', exact: true }).click();
  await page.getByRole('combobox', { name: 'Merge from', exact: true }).selectOption({ label: 'Decisions' });
  await page.getByRole('combobox', { name: 'Keep name', exact: true }).selectOption({ label: 'Thinking' });
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Merge with review', exact: true }).click();
  await expect(page.getByRole('combobox', { name: 'Merge from', exact: true })).toHaveValue('');
  await navigate(page, 'My library');
  await page.getByRole('button', { name: 'Open My Corrected Thinking Title', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Remove tag Thinking', exact: true })).toBeVisible();
  await closeDetail(page);
  await navigate(page, 'Settings & backup');
  await page.locator('.tag-manager .suggestion-row').filter({ has: page.getByText('Thinking', { exact: true }) }).getByRole('button', { name: 'Archive', exact: true }).click();
  await expect(page.getByText('Thinking (archived)', { exact: true })).toBeVisible();
  const backup = await exportBackup(page);
  expect(backup.document.entities.tagRedirects).toHaveLength(1);
  expect(backup.document.entities.tags.find(tag => tag.name === 'Thinking')?.archived).toBe(true);
});

test('an offline manual ISBN record enriches later without replacing a personal correction', async ({ page, context }) => {
  await mockLookup(page);
  const providerPaths: string[] = [];
  page.on('request', request => {
    if (request.url().startsWith('https://openlibrary.org/')) providerPaths.push(new URL(request.url()).pathname);
  });
  await page.goto('/');
  await context.setOffline(true);
  await page.getByRole('button', { name: 'Add a book', exact: true }).first().click();
  const add = page.getByRole('dialog', { name: 'Add a book', exact: true });
  await add.getByRole('tab', { name: 'Enter manually', exact: true }).click();
  await add.getByLabel('Title', { exact: true }).fill('Manual ISBN Record');
  await add.getByLabel('Author', { exact: true }).fill('Alex Reader');
  await add.getByLabel('ISBN', { exact: true }).fill('9780140328721');
  await add.getByRole('button', { name: 'Save book', exact: true }).click();
  await expect(add).not.toBeVisible();
  const detail = page.getByRole('dialog');
  await detail.getByLabel('Title', { exact: true }).fill('My Personal Corrected Title');
  await detail.getByLabel('Reading purpose', { exact: true }).fill('My own reason, kept after enrichment');
  await detail.getByRole('button', { name: 'Save details', exact: true }).click();
  await expect(detail.getByRole('heading', { name: 'My Personal Corrected Title', exact: true })).toBeVisible();
  await closeDetail(page);
  await context.setOffline(false);
  await enableOnline(page);
  await navigate(page, 'My library');
  await page.getByRole('button', { name: 'Open My Personal Corrected Title', exact: true }).click();
  await detail.getByRole('tab', { name: 'Sources', exact: true }).click();
  await detail.getByRole('button', { name: 'Refresh metadata', exact: true }).click();
  const choice = detail.getByRole('button', { name: /A Field Guide to Thinking/ });
  const diffHeading = detail.getByRole('heading', { name: 'Review provider changes', exact: true });
  await expect.poll(async () => await diffHeading.isVisible() || await choice.isVisible(), { timeout: 15000 }).toBe(true);
  if (await choice.isVisible()) await choice.click();
  await expect(diffHeading).toBeVisible();
  expect(providerPaths).toContain('/isbn/9780140328721.json');
  await detail.getByRole('button', { name: 'Apply provider refresh', exact: true }).click();
  await expect(diffHeading).not.toBeVisible();
  await detail.getByRole('tab', { name: 'Details', exact: true }).click();
  await expect(detail.getByLabel('Title', { exact: true })).toHaveValue('My Personal Corrected Title');
  await expect(detail.getByLabel('Reading purpose', { exact: true })).toHaveValue('My own reason, kept after enrichment');
  await closeDetail(page);
  const backup = await exportBackup(page);
  expect(backup.document.entities.works).toHaveLength(1);
  expect(backup.document.entities.metadataSnapshots).toHaveLength(1);
});
