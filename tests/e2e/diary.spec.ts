import { expect, test } from '@playwright/test';
import { addManual, addGoal, closeDetail, goalCard, navigate, exportBackup } from './helpers';

test.use({ serviceWorkers: 'block' });

test('primary and secondary Layers, purpose, notes and personal rating survive reload', async ({ page }) => {
  await page.goto('/');
  let detail = await addManual(page, 'Reading for a Reason', ['Physical', 'Digital']);
  await detail.getByRole('combobox', { name: 'Primary Layer', exact: true }).selectOption('fuel');
  await detail.getByLabel('Reading purpose', { exact: true }).fill("Today's debugging, not a permanent genre");
  await detail.getByRole('checkbox', { name: /^Software Applications/ }).check();
  await detail.getByRole('combobox', { name: 'Classification confidence', exact: true }).selectOption('tentative');
  await detail.getByLabel('Classification rationale', { exact: true }).fill('Useful for this task; I may revisit the placement.');
  await detail.getByRole('button', { name: 'Save details', exact: true }).click();
  await expect(detail.getByText(/Origin: user/)).toBeVisible();
  await detail.getByRole('tab', { name: 'Notes', exact: true }).click();
  await detail.getByRole('textbox', { name: 'Notes', exact: true }).fill('<script>window.diaryExecuted=true</script>\nA private idea മലയാളം');
  await detail.getByRole('combobox', { name: 'Your rating', exact: true }).selectOption('4');
  await detail.getByRole('button', { name: 'Save notes', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('notes are saved');
  await page.reload();
  await page.getByRole('button', { name: 'Open Reading for a Reason', exact: true }).click();
  detail = page.getByRole('dialog', { name: 'Reading for a Reason', exact: true });
  await expect(detail.getByRole('combobox', { name: 'Primary Layer', exact: true })).toHaveValue('fuel');
  await expect(detail.getByRole('checkbox', { name: /^Software Applications/ })).toBeChecked();
  await expect(detail.getByLabel('Reading purpose', { exact: true })).toHaveValue("Today's debugging, not a permanent genre");
  await expect(detail.getByRole('combobox', { name: 'Classification confidence', exact: true })).toHaveValue('tentative');
  await expect(detail.getByLabel('Classification rationale', { exact: true })).toHaveValue('Useful for this task; I may revisit the placement.');
  await detail.getByRole('tab', { name: 'Notes', exact: true }).click();
  await expect(detail.getByRole('textbox', { name: 'Notes', exact: true })).toHaveValue('<script>window.diaryExecuted=true</script>\nA private idea മലയാളം');
  await expect(detail.getByRole('combobox', { name: 'Your rating', exact: true })).toHaveValue('4');
  expect(await page.evaluate(() => 'diaryExecuted' in window)).toBe(false);
});

test('finish, correction and an explicit reread do not count session pages twice', async ({ page }) => {
  await page.goto('/');
  await addManual(page, 'A Reading Journey', ['Physical', 'Digital'], 200);
  await closeDetail(page);
  await addGoal(page, 'pages', 100);
  await addGoal(page, 'books', 3);
  await addGoal(page, 'minutes', 120);
  await navigate(page, 'My library');
  await page.getByRole('button', { name: 'Open A Reading Journey', exact: true }).click();
  const detail = page.getByRole('dialog');
  await detail.getByRole('tab', { name: 'Reading', exact: true }).click();
  await detail.getByLabel('Reading status', { exact: true }).selectOption('reading');
  await detail.getByLabel('Pages read this session', { exact: true }).fill('20');
  await detail.getByLabel('Minutes read', { exact: true }).fill('30');
  await detail.getByLabel('Current page', { exact: true }).fill('20');
  await detail.getByRole('button', { name: 'Log reading', exact: true }).click();
  await expect(detail.getByText('20 pages · 30 minutes · page 20', { exact: true })).toBeVisible();
  await detail.getByLabel('Reading status', { exact: true }).selectOption('paused');
  await detail.getByLabel('Reading status', { exact: true }).selectOption('reading');
  await detail.getByLabel('Reading status', { exact: true }).selectOption('finished');
  await detail.getByRole('button', { name: 'Correct', exact: true }).click();
  const correction = detail.locator('form').filter({ hasText: 'Correct reading entry' });
  await correction.getByLabel('Pages read this session', { exact: true }).fill('15');
  await correction.getByRole('button', { name: 'Save correction', exact: true }).click();
  await expect(detail.getByText('15 pages · 30 minutes · page 20', { exact: true })).toBeVisible();
  await detail.getByRole('button', { name: 'Start a reread', exact: true }).click();
  const logForm = detail.locator('form').filter({ hasText: 'A little reading, logged' });
  await logForm.getByLabel('Current page', { exact: true }).fill('');
  await logForm.getByLabel('Pages read this session', { exact: true }).fill('5');
  await logForm.getByLabel('Digital progress (%)', { exact: true }).fill('75');
  await logForm.getByRole('button', { name: 'Log reading', exact: true }).click();
  await detail.getByLabel('Reading status', { exact: true }).selectOption('finished');
  await closeDetail(page);
  await navigate(page, 'Reading');
  await expect(goalCard(page, 'pages read').locator('.goal-number')).toHaveText('20 / 100');
  await expect(goalCard(page, 'minutes read').locator('.goal-number')).toHaveText('30 / 120');
  await expect(goalCard(page, 'books finished').locator('.goal-number')).toHaveText('2 / 3');
  await page.getByText('How your progress is counted', { exact: true }).click();
  await expect(page.getByText(/Finishing a book adds no extra pages/)).toBeVisible();
  await page.reload();
  const backup = await exportBackup(page);
  expect(backup.document.entities.sessions).toHaveLength(2);
  expect(backup.document.entities.sessions.reduce((sum, session) => sum + session.pages, 0)).toBe(20);
  expect(backup.document.entities.readingCycles.filter(cycle => cycle.status === 'finished')).toHaveLength(2);
});

test('digital percentage with unknown pages stays a place marker, not invented pages', async ({ page }) => {
  await page.goto('/');
  const detail = await addManual(page, 'Digital Without Page Count', ['Digital']);
  await detail.getByRole('tab', { name: 'Reading', exact: true }).click();
  await detail.getByLabel('Digital progress (%)', { exact: true }).fill('42');
  await detail.getByRole('button', { name: 'Log reading', exact: true }).click();
  await expect(detail.getByText('0 pages · 0 minutes · 42%', { exact: true })).toBeVisible();
  await closeDetail(page);
  const backup = await exportBackup(page);
  expect(backup.document.entities.sessions[0].pages).toBe(0);
  expect(backup.document.entities.editions[0].metadata.pageCount).toBeUndefined();
});
