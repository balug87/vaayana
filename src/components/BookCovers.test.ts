// @vitest-environment jsdom
import 'fake-indexeddb/auto';
import { Blob as NodeBlob } from 'node:buffer';
import { createElement } from 'react';
import { cleanup, fireEvent, render, waitFor } from '@testing-library/react';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { BookCoverSettings } from './BookCoverSettings';
import { BookCoverPhoto } from './BookCoverPhoto';
import { BookCover } from './ui';
import { addBook, db, getSnapshot, initializeLibrary, saveSettings, saveUploadedCover } from '../data/repository';
import { exampleCoverJpeg } from '../data/cover-test-fixtures';
import { normalizeCoverPhoto } from '../services/cover-photo';
import { getNetworkPreferences, setNetworkPreferences } from '../services/network';
vi.mock('../services/cover-photo', () => ({ normalizeCoverPhoto: vi.fn() }));
beforeEach(async () => {
  vi.stubGlobal('Blob', NodeBlob);
  await db.delete(); await db.open(); await initializeLibrary();
  setNetworkPreferences({ onlineLookup: false, covers: false });
});
afterEach(async () => { cleanup(); await db.delete(); vi.unstubAllGlobals(); vi.restoreAllMocks(); vi.mocked(normalizeCoverPhoto).mockReset(); setNetworkPreferences({ onlineLookup: false, covers: false }); });
describe('actual global cover and local-photo controls', () => {
  it('uses one new opt-in to save all prerequisites, without starting a model or discovery call', async () => {
    await saveSettings({ loadCovers: true });
    const fetcher = vi.fn(); const worker = vi.fn(); vi.stubGlobal('fetch', fetcher); vi.stubGlobal('Worker', worker);
    const notify = vi.fn(); const settings = (await getSnapshot()).settings;
    const view = render(createElement(BookCoverSettings, { settings, notify }));
    expect((view.getByRole('checkbox', { name: 'Automatically fetch book covers' }) as HTMLInputElement).checked).toBe(false);
    fireEvent.click(view.getByRole('checkbox', { name: 'Automatically fetch book covers' }));
    await waitFor(async () => expect((await getSnapshot()).settings).toMatchObject({ autoFetchCovers: true, onlineAccess: true, loadCovers: true, modelConsent: false }));
    expect(fetcher).not.toHaveBeenCalled(); expect(worker).not.toHaveBeenCalled();
    view.rerender(createElement(BookCoverSettings, { settings: (await getSnapshot()).settings, notify }));
    fireEvent.click(view.getByRole('checkbox', { name: 'Automatically fetch book covers' }));
    expect(getNetworkPreferences()).toMatchObject({ covers: false, autoFetchCovers: false });
    await waitFor(async () => expect((await getSnapshot()).settings).toMatchObject({ autoFetchCovers: false, onlineAccess: true, loadCovers: false }));
  });
  it('saves/loads/removes a genuine prepared photo through real repository APIs without remote requests', async () => {
    const workId = await addBook({ title: 'Invented photo journal', authors: ['Example Author'] });
    const jpeg = new Blob([(await exampleCoverJpeg()).buffer as ArrayBuffer], { type: 'image/jpeg' });
    vi.mocked(normalizeCoverPhoto).mockResolvedValue({ blob: jpeg, width: 32, height: 48 });
    const fetcher = vi.fn(); vi.stubGlobal('fetch', fetcher);
    const notify = vi.fn(); let book = (await getSnapshot()).books[0];
    const view = render(createElement(BookCoverPhoto, { book, notify }));
    fireEvent.change(view.getByLabelText('Upload cover photo'), { target: { files: [new File(['photo'], 'private-original.png', { type: 'image/png' })] } });
    await waitFor(() => expect(notify).toHaveBeenCalledWith('Photo saved locally. It was not sent to a server.'));
    book = (await getSnapshot()).books[0];
    expect(book.cover).toMatchObject({ kind: 'uploaded', width: 32, height: 48 }); expect(book.id).toBe(workId);
    view.rerender(createElement(BookCoverPhoto, { book, notify }));
    expect(view.getByText('Replace photo')).toBeTruthy();
    const createObjectURL = vi.fn(() => 'blob:local-photo'); const revokeObjectURL = vi.fn();
    vi.stubGlobal('URL', { createObjectURL, revokeObjectURL });
    const cover = render(createElement(BookCover, { book, covers: false }));
    await waitFor(() => expect(cover.container.querySelector('img')?.getAttribute('src')).toBe('blob:local-photo'));
    cover.unmount(); expect(revokeObjectURL).toHaveBeenCalledWith('blob:local-photo');
    fireEvent.click(view.getByRole('button', { name: 'Remove custom cover' }));
    await waitFor(async () => expect((await getSnapshot()).books[0].cover?.kind).toBe('none'));
    book = (await getSnapshot()).books[0];
    expect(book.cover && 'revision' in book.cover && book.cover.revision).toBeTruthy();
    view.rerender(createElement(BookCoverPhoto, { book, notify }));
    fireEvent.change(view.getByLabelText('Upload cover photo'), { target: { files: [new File(['next'], 'replacement.png', { type: 'image/png' })] } });
    await waitFor(async () => expect((await getSnapshot()).books[0].cover?.kind).toBe('uploaded'));
    expect(fetcher).not.toHaveBeenCalled();
  });
  it('keeps the original photo when normalization fails or a newer photo wins during preparation', async () => {
    const workId = await addBook({ title: 'Invented concurrent photo' });
    const jpeg = new Blob([(await exampleCoverJpeg()).buffer as ArrayBuffer], { type: 'image/jpeg' });
    const notify = vi.fn(); const view = render(createElement(BookCoverPhoto, { book: (await getSnapshot()).books[0], notify }));
    vi.mocked(normalizeCoverPhoto).mockRejectedValueOnce(new Error('HEIC is not supported.'));
    const choose = () => fireEvent.change(view.getByLabelText('Upload cover photo'), { target: { files: [new File(['x'], 'x.heic', { type: 'image/heic' })] } });
    choose(); await view.findByText('HEIC is not supported.');
    expect((await getSnapshot()).books[0].cover?.kind).toBe('none');
    let finish!: (value: Awaited<ReturnType<typeof normalizeCoverPhoto>>) => void;
    vi.mocked(normalizeCoverPhoto).mockImplementationOnce(() => new Promise(resolve => { finish = resolve; }));
    choose(); await waitFor(() => expect(normalizeCoverPhoto).toHaveBeenCalledTimes(2));
    await saveUploadedCover(workId, { jpeg }, { expectedCoverRevision: null });
    const revision = (await getSnapshot()).books[0].cover;
    finish({ blob: jpeg, width: 32, height: 48 });
    await view.findByText('The cover changed while preparing the photo. Review it and try again.');
    expect((await getSnapshot()).books[0].cover).toEqual(revision);
  });
});
